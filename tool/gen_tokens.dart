// Generates lib/theme/tokens.g.dart from referenz/tokens.json and the colourway
// tables of the prototype. Run from the repository root:
//   dart run tool/gen_tokens.dart
//
// The test in test/theme/tokens_test.dart calls [generateTokens] and fails when
// the checked-in file is out of date.
import 'dart:convert';
import 'dart:io';

const tokensPath = 'referenz/tokens.json';
const prototypePath = 'referenz/horizont_prototyp.dc.html';
const outputPath = 'lib/theme/tokens.g.dart';

/// The role order of the prototype's colourway strings (`scheme()` in the
/// prototype).
const prototypeKeys = [
  'primary', 'onPrimary', 'pCont', 'onPCont', 'sec', 'onSec', 'sCont', //
  'onSCont', 'ter', 'onTer', 'tCont', 'onTCont', 'low', 'sc', 'high',
  'highest', 'bright', 'on', 'onVar', 'outline', 'outVar', 'inv', 'invOn',
];

/// Prototype colourway ids, in the order the settings list them.
const colourwayIds = ['blau', 'violett', 'gruen', 'orange', 'pink'];

void main() {
  File(outputPath).writeAsStringSync(generateTokens());
  stdout.writeln('Wrote $outputPath');
}

String generateTokens() {
  final tokens =
      jsonDecode(File(tokensPath).readAsStringSync()) as Map<String, dynamic>;
  final prototype = File(prototypePath).readAsStringSync();
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_tokens.dart from referenz/tokens.json and',
    )
    ..writeln('// referenz/horizont_prototyp.dc.html. Do not edit by hand.')
    ..writeln()
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln();

  _colours(out, tokens);
  _colourways(out, prototype);
  _numbers(out, tokens, 'spacing', 'TokenSpacing', 'space-');
  _numbers(out, tokens, 'radius', 'TokenRadius', 'radius-');
  _numbers(out, tokens, 'size', 'TokenSize', 'size-');
  return out.toString();
}

int _hex(String value) {
  final h = value.replaceFirst('#', '');
  return int.parse(h.length == 6 ? 'ff$h' : h, radix: 16);
}

String _lit(int argb) => '0x${argb.toRadixString(16).padLeft(8, '0')}';

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

void _colours(StringBuffer out, Map<String, dynamic> tokens) {
  final list = ((tokens['color'] as Map<String, dynamic>)['tokens'] as List)
      .cast<Map<String, dynamic>>();
  final byName = {for (final t in list) t['name'] as String: t['value']};

  Object? resolve(Object? value) {
    if (value is String && value.startsWith('{')) {
      return resolve(byName[value.substring(1, value.length - 1)]);
    }
    return value;
  }

  final light = <String, int>{};
  final dark = <String, int>{};
  final fixed = <String, int>{};
  for (final name in byName.keys) {
    final value = resolve(byName[name]);
    if (value is Map) {
      light[_camel(name)] = _hex(value['light'] as String);
      dark[_camel(name)] = _hex(value['dark'] as String);
    } else if (value is String) {
      fixed[_camel(name)] = _hex(value);
    }
  }

  void block(String name, Map<String, int> values) {
    out.writeln('  static const $name = <String, int>{');
    for (final e in values.entries) {
      out.writeln("    '${e.key}': ${_lit(e.value)},");
    }
    out.writeln('  };');
  }

  out.writeln(
    '/// Colour roles of the default (blue) style, by camelCase token name.',
  );
  out.writeln('abstract final class TokenColors {');
  block('light', light);
  block('dark', dark);
  out.writeln(
    '  /// Seeds and illustration colours, the same in light and dark.',
  );
  block('fixed', fixed);
  out.writeln('}');
  out.writeln();
}

void _colourways(StringBuffer out, String prototype) {
  out.writeln(
    '/// The five colourways of the prototype: [prototypeKeys] order.',
  );
  out.writeln('abstract final class TokenColourways {');
  out.writeln('  static const keys = <String>[');
  for (final k in prototypeKeys) {
    out.writeln("    '$k',");
  }
  out.writeln('  ];');
  out.writeln();
  out.writeln('  static const ids = <String>[');
  for (final id in colourwayIds) {
    out.writeln("    '$id',");
  }
  out.writeln('  ];');
  out.writeln();
  out.writeln('  static const light = <String, List<int>>{');
  final tables = <String, ({List<int> light, List<int> dark})>{};
  for (final id in colourwayIds) {
    final m = RegExp(
      '$id: \\{\\s*light: \'([0-9a-f,]+)\',\\s*dark: \'([0-9a-f,]+)\'',
    ).firstMatch(prototype);
    if (m == null) throw StateError('Colourway $id not found in prototype');
    List<int> parse(String s) => [for (final h in s.split(',')) _hex(h)];
    final t = (light: parse(m.group(1)!), dark: parse(m.group(2)!));
    if (t.light.length != prototypeKeys.length ||
        t.dark.length != prototypeKeys.length) {
      throw StateError('Colourway $id has the wrong number of roles');
    }
    tables[id] = t;
  }
  for (final e in tables.entries) {
    out.writeln("    '${e.key}': [${e.value.light.map(_lit).join(', ')}],");
  }
  out.writeln('  };');
  out.writeln();
  out.writeln('  static const dark = <String, List<int>>{');
  for (final e in tables.entries) {
    out.writeln("    '${e.key}': [${e.value.dark.map(_lit).join(', ')}],");
  }
  out.writeln('  };');
  out.writeln('}');
  out.writeln();
}

void _numbers(
  StringBuffer out,
  Map<String, dynamic> tokens,
  String group,
  String className,
  String prefix,
) {
  final list = ((tokens[group] as Map<String, dynamic>)['tokens'] as List)
      .cast<Map<String, dynamic>>();
  out.writeln('abstract final class $className {');
  for (final t in list) {
    final name = _camel((t['name'] as String).replaceFirst(prefix, ''));
    final px = double.parse((t['value'] as String).replaceAll('px', ''));
    out.writeln('  static const double ${_dartName(name)} = $px;');
  }
  out.writeln('}');
  out.writeln();
}

/// Space tokens are `space-1`; "1" is not an identifier.
String _dartName(String name) =>
    RegExp(r'^\d').hasMatch(name) ? 's$name' : name;
