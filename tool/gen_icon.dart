// Generates the launcher icon from lib/ui/logo_geometry.dart. Run from the
// repository root:
//   dart run tool/gen_icon.dart
//
// Writes the adaptive icon's vector drawables (foreground, monochrome), its
// background colour, and the legacy PNG mipmaps. The PNGs are rendered from
// an SVG of the same paths by ImageMagick (`magick`); minSdk 31 always uses
// the adaptive icon, so they are only a fallback.
//
// test/ui/icon_test.dart calls [generateIconFiles] and fails when the
// checked-in drawables are out of date.
import 'dart:io';

import 'package:horizont/ui/logo_geometry.dart';

const _res = 'android/app/src/main/res';

/// The colours of `LogoColors.brand` in lib/ui/horizont_logo.dart.
const _sky = '#0045FC';
const _ground = '#00228B';
const _sun = '#F26B3A';
const _line = '#B9C3FF';

const _legacy = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192};

void main() {
  for (final MapEntry(:key, :value) in generateIconFiles().entries) {
    File(key)
      ..createSync(recursive: true)
      ..writeAsStringSync(value);
    stdout.writeln('Wrote $key');
  }
  final svg = File('build/icon/ic_launcher.svg')..createSync(recursive: true);
  svg.writeAsStringSync(_svg());
  for (final MapEntry(:key, :value) in _legacy.entries) {
    final out = '$_res/mipmap-$key/ic_launcher.png';
    final result = Process.runSync('magick', [
      '-background', 'none', '-density', '${value * 4}', svg.path, //
      '-resize', '${value}x$value', out,
    ]);
    if (result.exitCode != 0) {
      stderr.writeln('magick failed for $out: ${result.stderr}');
      exitCode = 1;
      return;
    }
    stdout.writeln('Wrote $out');
  }
}

/// Path → file content of every generated text file.
Map<String, String> generateIconFiles() => {
  '$_res/drawable/ic_launcher_foreground.xml': _vector([
    _fill(_d(LogoGeometry.sun(), close: true), _sun),
    _fill(_d(LogoGeometry.ground(), close: true), _ground),
    ..._strokes(_line, _sun),
  ]),
  '$_res/drawable/ic_launcher_monochrome.xml': _vector([
    _fill(_d(LogoGeometry.sun(upperHalf: true), close: true), '#FFFFFF'),
    ..._strokes('#FFFFFF', '#FFFFFF'),
  ]),
  '$_res/values/ic_launcher_background.xml':
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by tool/gen_icon.dart. -->\n'
      '<resources>\n'
      '    <color name="ic_launcher_background">$_sky</color>\n'
      '</resources>\n',
  '$_res/mipmap-anydpi-v26/ic_launcher.xml':
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by tool/gen_icon.dart. -->\n'
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@color/ic_launcher_background" />\n'
      '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
      '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
      '</adaptive-icon>\n',
};

String _n(double v) => v.toStringAsFixed(2);

String _d(List<(double, double)> points, {bool close = false}) {
  final b = StringBuffer('M${_n(points.first.$1)},${_n(points.first.$2)}');
  for (final (x, y) in points.skip(1)) {
    b.write(' L${_n(x)},${_n(y)}');
  }
  if (close) b.write(' Z');
  return b.toString();
}

/// The horizon line and the reflections, as (path, colour, width).
List<(String, String, double)> _strokeShapes(String line, String sun) => [
  (
    _d(LogoGeometry.horizon(from: 8, to: LogoGeometry.size - 8)),
    line,
    LogoGeometry.horizonStroke,
  ),
  for (final (y, half) in LogoGeometry.reflections)
    (
      'M${_n(LogoGeometry.size / 2 - half)},${_n(y)} '
          'L${_n(LogoGeometry.size / 2 + half)},${_n(y)}',
      sun,
      LogoGeometry.reflectionStroke,
    ),
];

List<String> _strokes(String line, String sun) => [
  for (final (d, colour, width) in _strokeShapes(line, sun))
    '    <path\n'
        '        android:pathData="$d"\n'
        '        android:strokeColor="$colour"\n'
        '        android:strokeWidth="${_n(width)}"\n'
        '        android:strokeLineCap="round"\n'
        '        android:strokeLineJoin="round" />\n',
];

String _fill(String d, String colour) =>
    '    <path\n'
    '        android:pathData="$d"\n'
    '        android:fillColor="$colour" />\n';

String _vector(List<String> paths) =>
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Generated by tool/gen_icon.dart from lib/ui/logo_geometry.dart. -->\n'
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="108dp"\n'
    '    android:height="108dp"\n'
    '    android:viewportWidth="108"\n'
    '    android:viewportHeight="108">\n'
    '${paths.join()}'
    '</vector>\n';

/// The visible 72 of the icon, clipped to a circle, for the legacy PNGs.
String _svg() {
  const inset = LogoGeometry.visibleInset;
  const visible = LogoGeometry.size - 2 * inset;
  final strokes = [
    for (final (d, colour, width) in _strokeShapes(_line, _sun))
      '<path d="$d" fill="none" stroke="$colour" stroke-width="${_n(width)}" '
          'stroke-linecap="round" stroke-linejoin="round"/>',
  ].join();
  return '<svg xmlns="http://www.w3.org/2000/svg" '
      'viewBox="$inset $inset $visible $visible" width="$visible" height="$visible">'
      '<clipPath id="c"><circle cx="54" cy="54" r="${visible / 2}"/></clipPath>'
      '<g clip-path="url(#c)">'
      '<rect x="0" y="0" width="108" height="108" fill="$_sky"/>'
      '<path d="${_d(LogoGeometry.sun(), close: true)}" fill="$_sun"/>'
      '<path d="${_d(LogoGeometry.ground(), close: true)}" fill="$_ground"/>'
      '$strokes</g></svg>';
}
